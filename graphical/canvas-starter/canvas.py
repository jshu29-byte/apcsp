"""
Provided by your teacher. Do not edit this file.

Drawing with transforms. Each function here works exactly like the pygame.draw
function with the same name, except that it first moves and scales what it draws
according to the transforms that are currently pushed.

    push_transform(x, y, scale)   from now on, draw shifted by (x, y) and
                                  scaled by `scale`
    pop_transform()               undo the most recent push_transform()

Pushes stack up: after two pushes, a drawing is transformed by both. Every
push_transform() in draw() needs a matching pop_transform() before draw() ends.
"""

from dataclasses import dataclass

import pygame


@dataclass(frozen=True)
class Transform:
    """Maps a local point (px, py) to (x + scale * px, y + scale * py)."""

    x: float = 0  # how far right the local origin is moved
    y: float = 0  # how far down the local origin is moved
    scale: float = 1  # how much bigger (or smaller, if under 1) to draw


# Every transform pushed and not yet popped, outermost first.
# An empty stack means "draw things exactly where they say."
_stack = []


# ---------------------------------------------------------------------------
# Pushing and popping


def push_transform(x=0, y=0, scale=1):
    """Shift everything drawn after this by (x, y), and scale it by `scale`."""
    _stack.append(Transform(x, y, scale))


def pop_transform():
    """Undo the most recent push_transform()."""
    if len(_stack) == 0:
        raise RuntimeError(
            "pop_transform() was called without a matching push_transform()."
        )
    _stack.pop()


def with_transform(x, y, scale, draw_fn, data=None):
    """Call draw_fn with a transform pushed, then pop it again.

    If `data` is given, it is passed to draw_fn; otherwise draw_fn is called
    with no arguments.
    """
    push_transform(x, y, scale)
    if data is None:
        draw_fn()
    else:
        draw_fn(data)
    pop_transform()


def finish_frame():
    """Called by main.py after each draw(). You never need to call this.

    Returns None if every push was popped. Otherwise empties the stack and
    returns a message describing the problem.
    """
    if len(_stack) == 0:
        return None
    count = len(_stack)
    _stack.clear()
    if count == 1:
        times = "time"
    else:
        times = "times"
    return (
        f"draw() finished, but push_transform() was called {count} more {times}\n"
        f"than pop_transform(). Every push_transform() needs a pop_transform()."
    )


# ---------------------------------------------------------------------------
# Applying the transforms


def _apply(t, px, py):
    """Map one point through one transform."""
    return t.x + t.scale * px, t.y + t.scale * py


def _to_screen(point):
    """Map a local point through every pushed transform, innermost first."""
    px, py = point
    for t in reversed(_stack):
        px, py = _apply(t, px, py)
    return round(px), round(py)


def _to_screen_points(points):
    """Map every point in a list of points."""
    screen_points = []
    for p in points:
        screen_points.append(_to_screen(p))
    return screen_points


def _total_scale():
    """How much bigger things are drawn, counting every pushed transform."""
    total = 1
    for t in _stack:
        total = total * t.scale
    return total


def _to_screen_rect(rect):
    """Map a rectangle by mapping two opposite corners.

    Rounding both corners (rather than the corner and the size) keeps shapes
    that share an edge from leaving a one-pixel gap between them.
    """
    left, top, width, height = rect
    x1, y1 = _to_screen((left, top))
    x2, y2 = _to_screen((left + width, top + height))
    return pygame.Rect(x1, y1, x2 - x1, y2 - y1)


def _to_screen_length(length):
    """Scale a length, like a radius."""
    return round(length * _total_scale())


def _to_screen_width(width):
    """Scale a line width. A width of 0 means "filled in," so it stays 0;
    any visible line stays at least one pixel wide."""
    if width <= 0:
        return width
    return max(1, round(width * _total_scale()))


# ---------------------------------------------------------------------------
# Drawing: same as pygame.draw, but transformed


def rect(surface, color, rect, width=0, border_radius=0):
    """Like pygame.draw.rect."""
    return pygame.draw.rect(
        surface,
        color,
        _to_screen_rect(rect),
        _to_screen_width(width),
        _to_screen_length(border_radius),
    )


def ellipse(surface, color, rect, width=0):
    """Like pygame.draw.ellipse."""
    return pygame.draw.ellipse(
        surface, color, _to_screen_rect(rect), _to_screen_width(width)
    )


def circle(surface, color, center, radius, width=0):
    """Like pygame.draw.circle."""
    return pygame.draw.circle(
        surface,
        color,
        _to_screen(center),
        _to_screen_length(radius),
        _to_screen_width(width),
    )


def arc(surface, color, rect, start_angle, stop_angle, width=1):
    """Like pygame.draw.arc. Angles are in radians, as in pygame."""
    return pygame.draw.arc(
        surface,
        color,
        _to_screen_rect(rect),
        start_angle,
        stop_angle,
        _to_screen_width(width),
    )


def line(surface, color, start_pos, end_pos, width=1):
    """Like pygame.draw.line."""
    return pygame.draw.line(
        surface,
        color,
        _to_screen(start_pos),
        _to_screen(end_pos),
        _to_screen_width(width),
    )


def lines(surface, color, closed, points, width=1):
    """Like pygame.draw.lines."""
    return pygame.draw.lines(
        surface, color, closed, _to_screen_points(points), _to_screen_width(width)
    )


def polygon(surface, color, points, width=0):
    """Like pygame.draw.polygon."""
    return pygame.draw.polygon(
        surface, color, _to_screen_points(points), _to_screen_width(width)
    )